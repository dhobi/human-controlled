// The rules, against small fixed examples: each is a case a real repository
// showed, so a change that breaks one is visible before it lands.

import { test } from "node:test";
import assert from "node:assert/strict";
import { badge } from "../badge.mjs";
import { AI_TRAILER, isPolicyText, isBan, attributeRules, mirrorReason, countBursts, verdictOf } from "../human-controlled.mjs";

test("an AI trailer names an AI tool, a human co-author does not count", () => {
  assert.ok(AI_TRAILER.test("Fix it\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>"));
  assert.ok(AI_TRAILER.test("Fix it\n\nAssisted-By: GitHub Copilot"));
  assert.ok(!AI_TRAILER.test("Fix it\n\nCo-authored-by: Jane Doe <jane@example.com>"));
});

test("a policy is a rule about AI, not a mention of it", () => {
  assert.ok(isPolicyText("We welcome the thoughtful use of AI tools when contributing, but ask all contributors to follow two principles."));
  assert.ok(isPolicyText("Contributions must not include content generated by large language models."));
  assert.ok(!isPolicyText("Built with an AI assistant."));
  // "ai" in lower case is a word in many languages, not the acronym
  assert.ok(!isPolicyText("Il pleut, ai-je dit, and the rules are simple."));
});

test("a ban refuses AI and welcomes it nowhere", () => {
  // Servo
  assert.ok(isBan("Contributions must not include content generated by large language models or other probabilistic tools, including but not limited to Copilot or ChatGPT."));
  // vite
  assert.ok(!isBan("We welcome the thoughtful use of AI tools when contributing to Vite."));
  // ripgrep: AI welcome, only autonomous agents refused
  assert.ok(!isBan("Using AI (i.e., LLMs) as tools for coding is welcome.\nAutonomous agents are not allowed to be used for contributing to this project."));
});

test("a markdown table is read line by line, not as one sentence", () => {
  // LLMRouter: a feature table that names AI providers once read as a ban
  const table = "| Area | Upstream | Here |\n|---|---|---|\n| Gateway formats | OpenAI, Claude, Gemini | Same |\n| Keys | must not be shared | encrypted |";
  assert.ok(!isBan(table));
});

test(".gitattributes marks generated and vendored files", () => {
  const rules = attributeRules("*.mesh.ts linguist-generated\n/dist/** linguist-vendored\ndocs/*.md -diff\n# comment linguist-generated");
  const marked = (path) => rules.some((r) => r.test(path));
  assert.ok(marked("taoot/bedsit/src/titanic.mesh.ts"));
  assert.ok(marked("dist/app.js"));
  assert.ok(!marked("src/dist.js"));
  assert.ok(!marked("docs/readme.md"));
});

const commit = (login, viaPR = null) => ({ author: { user: { login } }, viaPR });
const many = (n, f) => Array.from({ length: n }, (_, i) => f(i));

test("a mirror says so, or many people commit and almost nothing comes through a PR", () => {
  assert.match(mirrorReason("[MIRROR] Official Gentoo ebuild repository", []), /description/);
  // the Linux kernel: hundreds of people, no PRs
  assert.match(mirrorReason("Linux kernel source tree", many(481, (i) => commit(`dev${i % 205}`))), /205 people/);
  // a solo developer pushing to main is not a mirror
  assert.equal(mirrorReason(null, many(159, () => commit("dhobi"))), null);
  // too few commits to tell
  assert.equal(mirrorReason(null, many(40, (i) => commit(`dev${i}`))), null);
  // a project that works through PRs
  assert.equal(mirrorReason(null, many(300, (i) => commit(`dev${i % 50}`, i))), null);
});

const minute = 60e3;
const change = (who, at, lines = 500, reviewed = false) => ({ who, at: Date.UTC(2026, 0, 1) + at, lines, reviewed });

test("a burst is three large unreviewed changes by one author within an hour", () => {
  assert.equal(countBursts([change("a", 0), change("a", 20 * minute), change("a", 40 * minute)]), 1);
  assert.equal(countBursts(many(6, (i) => change("a", i * 10 * minute))), 2);
  // spread over a day: a human's pace
  assert.equal(countBursts([change("a", 0), change("a", 8 * 60 * minute), change("a", 16 * 60 * minute)]), 0);
  // reviewed, small, or by different people: not a burst
  assert.equal(countBursts(many(3, (i) => change("a", i * minute, 500, true))), 0);
  assert.equal(countBursts(many(3, (i) => change("a", i * minute, 300))), 0);
  assert.equal(countBursts(many(3, (i) => change(`p${i}`, i * minute))), 0);
});

test("the verdict and its caps", () => {
  const allows = { at: "AI_POLICY.md", ban: false };
  const bans = { at: "https://example.org/ai", ban: true };
  assert.deepEqual(verdictOf({ policy: allows, aiSeen: 289, bursts: 9 })[1], null);
  assert.match(verdictOf({ policy: allows, aiSeen: 0, bursts: 0 })[0], /^AI-aware/);
  assert.deepEqual(verdictOf({ policy: bans, aiSeen: 0, bursts: 0 }), ["AI banned by policy (https://example.org/ai)", null]);
  assert.equal(verdictOf({ policy: bans, aiSeen: 102, bursts: 0 })[1], 0.25);
  assert.equal(verdictOf({ policy: null, aiSeen: 49, bursts: 0 })[1], 0.4);
  // hiding the footers does not escape the cap
  assert.deepEqual(verdictOf({ policy: null, aiSeen: 0, bursts: 2 })[1], 0.4);
  assert.deepEqual(verdictOf({ policy: null, aiSeen: 2, bursts: 1 }), ["no AI visible, and no policy", null]);
});

test("the badge: a score, the safeguards of a ban, or grey with no score", () => {
  assert.deepEqual(badge({ total: 0.63 }), { schemaVersion: 1, label: "human-controlled", message: "63%", color: "yellow" });
  assert.equal(badge({ total: 0.84, aiBan: "https://example.org/ai" }).label, "safeguards");
  assert.equal(badge({ total: 0.84 }).color, "green");
  assert.equal(badge({ total: 0.4 }).color, "orange");
  assert.equal(badge({ total: null, tooLittle: "2 commits" }).message, "no score yet");
  assert.equal(badge({ total: null, mirror: "description" }).message, "mirror, no score");
  assert.equal(badge(null).message, "unavailable");
});
